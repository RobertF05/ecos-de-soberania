def calcular_resultado(respuestas_usuario):
    """
    Calcula el puntaje global y asigna el Arquetipo de Identidad Soberana.
    """
    total_obtenido = 0
    max_posible = len(PREGUNTAS_DILEMAS) * 100
    detalles = []

    # Mapa de respuestas
    dict_preguntas = {p['id']: p for p in PREGUNTAS_DILEMAS}

    for r in respuestas_usuario:
        p_id = r.get('pregunta_id')
        op_id = r.get('opcion_id')
        pregunta = dict_preguntas.get(p_id)
        if pregunta:
            for op in pregunta['opciones']:
                if op['id'] == op_id:
                    total_obtenido += op['ponderacion']
                    detalles.append({
                        "pregunta_id": p_id,
                        "trayecto": pregunta['trayecto'],
                        "opcion_elegida": op_id,
                        "ponderacion": op['ponderacion'],
                        "reflexion": op['reflexion'],
                        "cita": op['cita']
                    })
                    break

    porcentaje = int((total_obtenido / max_posible) * 100) if max_posible > 0 else 0

    if porcentaje >= 90:
        arquetipo = "Centinela de la Dignidad Nacional"
        subtitulo = "Conciencia Histórica Plena e Inquebrantable"
        descripcion = "Tus decisiones reflejan el temple de Sandino, la firmeza de Zeledón y el heroísmo de San Jacinto. Comprendes con lucidez que la soberanía de Nicaragua reside en la autodeterminación popular, la unidad multiétnica y la defensa inclaudicable de nuestra identidad."
        insignia = "guardabarranco_oro"
    elif porcentaje >= 70:
        arquetipo = "Defensor de la Memoria Colectiva"
        subtitulo = "Compromiso Patriótico y Soberano Activo"
        descripcion = "Posees una sólida comprensión de las encrucijadas históricas de Nicaragua. Valoras la dignidad y las conquistas sociales, reconociendo que la independencia se construye día a día en cada ámbito de la sociedad."
        insignia = "sacuanjoche_plata"
    elif porcentaje >= 50:
        arquetipo = "Explorador de las Raíces Patrias"
        subtitulo = "Conciencia en Proceso de Despertar"
        descripcion = "Identificas momentos clave de nuestra historia, aunque en ciertos dilemas persiste la tentación de confiar en soluciones foráneas o pactos que históricamente debilitaron a la nación. ¡La memoria histórica es tu mejor guía!"
        insignia = "volcan_bronce"
    else:
        arquetipo = "Aprendiz de la Historia Nacional"
        subtitulo = "Invitación a Redescubrir la Epopeya de Nicaragua"
        descripcion = "El recorrido del museo digital te brindará las herramientas y evidencias para comprender por qué la soberanía y la autodeterminación son los pilares fundamentales sobre los cuales se erige la patria."
        insignia = "madrono_semilla"

    return {
        "porcentaje": porcentaje,
        "arquetipo": arquetipo,
        "subtitulo": subtitulo,
        "descripcion": descripcion,
        "insignia": insignia,
        "detalles": detalles
    }
